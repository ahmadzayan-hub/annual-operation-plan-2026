// Synthetic fixtures only. Exercises the built package under a Pages-like subpath.
const { chromium } = require('playwright');
const { source: axe } = require('axe-core');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const http = require('node:http');
const ROOT = path.resolve(__dirname, '../dist');
const PREFIX = '/annual-operation-plan-2026/';
const MIME = {'.html':'text/html', '.js':'text/javascript', '.svg':'image/svg+xml', '.webmanifest':'application/manifest+json', '.json':'application/json'};
const server = http.createServer((req,res) => {
  const pathname = new URL(req.url, 'http://localhost').pathname;
  const name = pathname.startsWith(PREFIX) ? pathname.slice(PREFIX.length) || 'index.html' : '';
  const file = path.resolve(ROOT, name);
  if (!name || !file.startsWith(ROOT + path.sep) || !fs.existsSync(file) || !fs.statSync(file).isFile()) { res.writeHead(404).end(); return; }
  res.writeHead(200, {'Content-Type':MIME[path.extname(file)] || 'application/octet-stream', 'Cache-Control':'no-cache'});
  fs.createReadStream(file).pipe(res);
});
async function audit(page, label) {
  await page.addScriptTag({content:axe});
  const violations = await page.evaluate(async () => (await axe.run(document, {runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21a','wcag21aa','wcag22aa']}})).violations.map(v=>({id:v.id,impact:v.impact,nodes:v.nodes.map(n=>n.target)})));
  assert.deepEqual(violations, [], label + ': accessibility violations');
}
